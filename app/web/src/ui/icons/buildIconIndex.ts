// Builds the generated icon modules from the SVG files. Used by `npm run icons` and by the staleness
// test, so it takes the files as data and never touches the disk.

export type IconKind = 'line' | 'color';

export interface IconFile {
  name: string;
  kind: IconKind;
  svg: string;
}

const svgPattern = /^<svg\b[^>]*\bviewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>\s*$/;

// `delete` is a reserved word, so every export carries the prefix.
export function glyphExport(name: string): string {
  const words = name.split('-').map((w) => (w[0] as string).toUpperCase() + w.slice(1));
  return `icon${words.join('')}`;
}

export interface IconModules {
  /** glyphs.ts: one named export per icon, so a bundle keeps only the icons it imports. */
  glyphs: string;
  /** index.ts: every icon by name, for the gallery and tests. Importing it ships the whole set. */
  index: string;
}

export function buildIconModules(files: IconFile[], illustrations: string[]): IconModules {
  const sorted = [...files].sort((a, b) => (a.name < b.name ? -1 : 1));
  const parsed = sorted.map(({ name, kind, svg }) => {
    const match = svgPattern.exec(svg);
    if (!match) throw new Error(`${name}: not a single <svg> with a viewBox`);
    const [, viewBox, body] = match as unknown as [string, string, string];
    return { name, data: { kind, viewBox, body: body.replace(/\n/g, '') } };
  });
  const glyphs = parsed.map(
    ({ name, data }) => `export const ${glyphExport(name)}: Glyph = ${JSON.stringify(data)};`,
  );
  // Inlined rather than re-exported: a bundler cannot split one module across chunks, so sharing
  // glyphs.ts with the gallery would make every page load the whole set.
  const entries = parsed.map(
    ({ name, data }) => `  ${JSON.stringify(name)}: ${JSON.stringify(data)},`,
  );
  const names = [...illustrations].sort().map((n) => `  ${JSON.stringify(n)},`);
  const header = '// Generated by `npm run icons` from ./line, ./color and public/illustrations.';
  return {
    glyphs: [
      `${header} Do not edit.`,
      '',
      'export interface Glyph {',
      "  kind: 'line' | 'color';",
      '  viewBox: string;',
      '  body: string;',
      '}',
      '',
      ...glyphs,
      '',
    ].join('\n'),
    index: [
      `${header} Do not edit.`,
      '// App code imports from ./glyphs instead; this file carries every icon.',
      '',
      'export const icons = {',
      ...entries,
      '} as const;',
      '',
      'export type IconName = keyof typeof icons;',
      'export const iconNames = Object.keys(icons) as IconName[];',
      '',
      'export const illustrationNames = [',
      ...names,
      '] as const;',
      '',
      'export type IllustrationName = (typeof illustrationNames)[number];',
      '',
    ].join('\n'),
  };
}
