// Builds the generated icon index from the SVG files. Used by `npm run icons` and by the staleness
// test, so it takes the files as data and never touches the disk.

export type IconKind = 'line' | 'color';

export interface IconFile {
  name: string;
  kind: IconKind;
  svg: string;
}

const svgPattern = /^<svg\b[^>]*\bviewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>\s*$/;

export function buildIconIndex(files: IconFile[], illustrations: string[]): string {
  const entries = [...files]
    .sort((a, b) => (a.name < b.name ? -1 : 1))
    .map(({ name, kind, svg }) => {
      const match = svgPattern.exec(svg);
      if (!match) throw new Error(`${name}: not a single <svg> with a viewBox`);
      const [, viewBox, body] = match as unknown as [string, string, string];
      const data = { kind, viewBox, body: body.replace(/\n/g, '') };
      return `  ${JSON.stringify(name)}: ${JSON.stringify(data)},`;
    });
  const names = [...illustrations].sort().map((n) => `  ${JSON.stringify(n)},`);
  return [
    '// Generated by `npm run icons` from ./line, ./color and public/illustrations. Do not edit.',
    '',
    'export const icons = {',
    ...entries,
    '} as const;',
    '',
    'export type IconName = keyof typeof icons;',
    'export const iconNames = Object.keys(icons) as IconName[];',
    '',
    'export const illustrationNames = [',
    ...names,
    '] as const;',
    '',
    'export type IllustrationName = (typeof illustrationNames)[number];',
    '',
  ].join('\n');
}
